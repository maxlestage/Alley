#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fill_and_parse() {
        assert_eq!(
            fill("{} · disparaît à {}", &["3 présents", "00:00"]),
            "3 présents · disparaît à 00:00"
        );
        assert_eq!(Lang::parse("en-GB"), Some(Lang::En));
        assert_eq!(Lang::parse("es-419"), Some(Lang::Es));
        assert_eq!(Lang::parse("de"), None);
    }

    #[test]
    fn placeholders_match_in_every_language() {
        let pick = |t: &Texts| {
            vec![
                t.create_room,
                t.room_meta,
                t.present_one,
                t.present_many,
                t.in_call_one,
                t.in_call_many,
                t.encrypted_fp,
                t.room_welcome,
                t.typing_one,
                t.typing_many,
                t.invite_title,
                t.guest_name,
                t.err_generic,
            ]
        };
        for (a, (b, c)) in pick(&FR).iter().zip(pick(&EN).iter().zip(pick(&ES).iter())) {
            let n = a.matches("{}").count();
            assert_eq!(n, b.matches("{}").count(), "{a} / {b}");
            assert_eq!(n, c.matches("{}").count(), "{a} / {c}");
        }
    }
}
