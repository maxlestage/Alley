//! Les trois langues d'Alley : français, anglais, espagnol. Chaque texte
//! existe dans les trois (le compilateur y veille : un champ oublié ne
//! compile pas). `{}` marque une valeur à insérer ([`fill`]).

use std::cell::Cell;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    Fr,
    En,
    Es,
}

pub const LANGS: [Lang; 3] = [Lang::Fr, Lang::En, Lang::Es];

impl Lang {
    pub fn code(self) -> &'static str {
        match self {
            Lang::Fr => "fr",
            Lang::En => "en",
            Lang::Es => "es",
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Lang::Fr => "Français",
            Lang::En => "English",
            Lang::Es => "Español",
        }
    }

    /// `fr`, `en-GB`, `es-419`… ; `None` pour une autre langue.
    pub fn parse(code: &str) -> Option<Lang> {
        let code = code.trim().to_ascii_lowercase();
        let base = code.split(['-', '_']).next().unwrap_or_default();
        match base {
            "fr" => Some(Lang::Fr),
            "en" => Some(Lang::En),
            "es" => Some(Lang::Es),
            _ => None,
        }
    }

    /// Le chemin des pages dans cette langue : `""`, `"/en"`, `"/es"`.
    pub fn prefix(self) -> &'static str {
        match self {
            Lang::Fr => "",
            Lang::En => "/en",
            Lang::Es => "/es",
        }
    }

    pub fn texts(self) -> &'static Texts {
        match self {
            Lang::Fr => &FR,
            Lang::En => &EN,
            Lang::Es => &ES,
        }
    }
}

thread_local! {
    static CURRENT: Cell<Lang> = const { Cell::new(Lang::Fr) };
}

pub fn lang() -> Lang {
    CURRENT.with(Cell::get)
}

pub fn set_lang(lang: Lang) {
    CURRENT.with(|c| c.set(lang));
}

/// Les textes de la langue choisie.
pub fn t() -> &'static Texts {
    lang().texts()
}

/// Remplace chaque `{}` par la valeur suivante.
pub fn fill(template: &str, values: &[&str]) -> String {
    let mut out = String::with_capacity(template.len() + 16);
    let mut values = values.iter();
    let mut rest = template;
    while let Some(i) = rest.find("{}") {
        out.push_str(&rest[..i]);
        out.push_str(values.next().copied().unwrap_or_default());
        rest = &rest[i + 2..];
    }
    out.push_str(rest);
    out
}

